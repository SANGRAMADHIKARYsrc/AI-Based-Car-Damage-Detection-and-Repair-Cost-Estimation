"""Phase 13 — Inspection Report Generator.

Formats and exports multimodal car damage inspection reports:
1. Formatted JSON audit file
2. High-resolution annotated inspection overlay image
3. Markdown inspection certificate
"""

import json
from pathlib import Path
from typing import Any, Dict
import cv2


class InspectionReportGenerator:
    """Exports structured damage audit certificates and images."""

    @staticmethod
    def export_report(
        inspection_result: Dict[str, Any],
        output_dir: str = "reports",
        sample_id: str = "sample_inspection",
    ) -> Dict[str, str]:
        """Save JSON report, Markdown certificate, and annotated image."""
        out_path = Path(output_dir)
        out_path.mkdir(parents=True, exist_ok=True)

        report_data = inspection_result["report"]
        annotated_img = inspection_result["annotated_image"]

        # 1. Save JSON
        json_path = out_path / f"{sample_id}_report.json"
        with open(json_path, "w", encoding="utf-8") as f:
            json.dump(report_data, f, indent=2)

        # 2. Save Image
        img_path = out_path / f"{sample_id}_annotated.jpg"
        cv2.imwrite(str(img_path), annotated_img)

        # 3. Save Markdown Certificate
        md_path = out_path / f"{sample_id}_summary.md"
        cost_est = report_data["repair_cost_estimate"]
        summary = report_data["inspection_summary"]
        veh = report_data["vehicle_profile"]

        md_content = f"""# Vehicle Damage Inspection & Repair Cost Estimate

**Report ID:** `{sample_id}`  
**Vehicle:** {veh['year']} {veh['make']} ({veh['brand_tier'].capitalize()})  
**Operability:** {"Runs & Drives" if veh['operable'] else "Inoperable"}  

---

## Actuarial Repair Cost Estimate
- **Estimated Repair Cost:** **${cost_est['estimated_cost_usd']:,.2f}**
- **90% Prediction Interval:** **${cost_est['confidence_interval_90_usd']['lower_bound']:,.2f} — ${cost_est['confidence_interval_90_usd']['upper_bound']:,.2f}**
- **Primary Cost Driver:** {cost_est['primary_cost_driver']}

---

## Visual Damage Summary
- **Detected Damage Instances:** {summary['total_damage_instances']}
- **Primary Impact Sector:** {summary['primary_impact_sector']}
- **Primary Damaged Component:** `{summary['primary_damaged_component']}`
- **Damage Severity Index (DSI):** {summary['max_dsi_score']} ({summary['composite_severity'].upper()})

### Damage Itemization
| # | Damage Type | Component | Sector | Severity | DSI | Conf |
|---|---|---|---|---|---|---|
"""
        for i, d in enumerate(report_data["detected_damages"], 1):
            md_content += f"| {i} | **{d['damage_type']}** | `{d['component']}` | {d['copart_sector']} | {d['severity_grade']} | {d['dsi_score']} | {d['confidence']:.2f} |\n"

        md_content += f"""
---
*Automated multi-stage deep learning report generated by Car Damage AI.*
"""
        with open(md_path, "w", encoding="utf-8") as f:
            f.write(md_content)

        return {
            "json_path": str(json_path),
            "image_path": str(img_path),
            "markdown_path": str(md_path),
        }
